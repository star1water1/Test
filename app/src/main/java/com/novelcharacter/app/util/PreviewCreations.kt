package com.novelcharacter.app.util

/**
 * 복원 미리보기가 **이 파일이 앞서 만든 항목**에 붙이는 임시 id (B-233).
 *
 * ## 무엇이 문제였는가
 *
 * 가져오기는 한 행을 넣은 뒤 그것을 정체성 색인에 **즉시 등재**하므로, 같은 시트에서 같은
 * 대상을 두 번 쓰는 파일은 *신규 1 + 갱신 1*이 된다. 미리보기는 DB만 보고 등재하지 않아
 * 같은 파일을 **신규 2**로 셌다 — 유실은 없지만 **예고한 숫자가 실행되지 않는다.**
 *
 * ## 왜 음수 연번인가 — 세 가지가 한꺼번에 걸린다
 *
 * 1. **실존 id와 겹치지 않는다.** Room의 id는 1부터라 음수는 어떤 행도 아니다. 미리보기는
 *    DB에 쓰지 않으므로 이 값이 저장될 길도 없다.
 * 2. **서로와도 겹치지 않는다.** 전부 같은 값(예: 0)으로 두면 [ImportLookupIndex.put]이
 *    *같은 행이 옮겨 온 것*으로 보아 **앞 신규의 키를 끊는다** — 한 파일에서 새 항목을 둘
 *    만들면 첫째가 색인에서 사라진다. 연번이라야 그 역효과가 없다.
 * 3. **[ANALYSIS_CREATED_NOVEL_ID]와도 겹치지 않는다.** 그 값은 *"가져오기가 새로 만들어
 *    배정할 작품"*을 뜻하는 **예약 표지**라, 발급기가 그 자리를 다시 내주면 미리보기가
 *    서로 다른 두 가지를 같은 것으로 본다. 그래서 발급은 그 아래에서 시작한다.
 *
 * ## 쓰는 쪽 규약 (규약 R-33의 셋째 — B-233)
 *
 * `analyze*`는 매칭이 빈손이면 `newCount++` 뒤에 **가져오기가 만들 그 항목**을
 * `new*From(...)`으로 지어 `copy(id = ids.mint())`로 표를 매기고, 그 행이 매칭에 쓰는
 * 색인·맵에 그대로 등재한다. `new*From`은 짝 `import*`가 insert 하는 값을 **같은 함수로**
 * 짓는다 — 미리보기가 제 손으로 지으면 그것이 바로 R-33이 없애려던 *손으로 짠 두 벌*이다.
 *
 * **발급기는 시트 함수의 지역 변수로 둘 것** — 서비스에 매달면 분석이 끝나도 남는다.
 */
class PreviewIdMinter {

    private var next = ANALYSIS_CREATED_NOVEL_ID - 1

    /** 이 행이 만들 항목에 붙일 임시 id. 부를 때마다 내려간다. */
    fun mint(): Long = next--
}

/**
 * 미리보기에서 *"어디에도 없어 가져오기가 새로 만들어 배정할 작품"*을 뜻하는 표지값.
 *
 * 캐릭터 행의 작품 제목이 기존 작품 어디에도 없으면 가져오기는 **새 작품을 만들어 배정**하므로,
 * 미리보기는 그 행을 **기존의 어떤 novelId와도 다른 값**으로 세어야 같은 답이 된다.
 * DB id는 1부터라 이 값은 실존하지 않고, 미리보기는 DB에 쓰지 않으므로 저장될 길도 없다.
 *
 * **[PreviewIdMinter]와 자리를 나눠 쓴다** — 발급기는 이 값 **아래**에서 시작한다(위 3번).
 */
const val ANALYSIS_CREATED_NOVEL_ID = -1L

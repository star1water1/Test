package com.novelcharacter.app.util

/**
 * 정규식 문자 클래스를 **두 엔진에서 같은 뜻이 되도록 못박은 자리** — 단일 소스.
 *
 * ## 왜 이 파일이 있나 — 약칭은 엔진마다 뜻이 다르다
 *
 * **데스크톱 JVM의 `java.util.regex`와 안드로이드의 그것은 같은 이름의 다른 엔진이다.**
 * 안드로이드 쪽은 ICU(`com.android.icu.util.regex`)이고, 약칭의 뜻이 이만큼 갈린다
 * (2026.08.21에 ICU 74와 OpenJDK 21로 BMP 전 코드포인트를 대조해 실측한 수다):
 *
 * | 약칭 | 데스크톱 JVM | 안드로이드(ICU) |
 * |---|---:|---:|
 * | `\d` | `[0-9]` — **10자** | 유니코드 `Nd` 전체 — **370자** (전각 `１`·아랍 `١`·타이 `๑` …) |
 * | `\s` | ASCII 6자 | 유니코드 공백 — **25자** (NBSP `U+00A0`·전각 공백 `U+3000` …) |
 * | `\w` | `[A-Za-z0-9_]` — **63자** | 유니코드 단어 문자 — **50,802자** |
 * | `\b` | 위 `\w`로 정의된다 | 위 `\w`로 정의된다 — 따라서 같이 갈린다 |
 *
 * **이것이 왜 위험한가:** 이 저장소의 자동 검증은 전부 데스크톱 JVM에서 돈다(순수 JVM 시험
 * 하네스 · 차분 컴파일 · 프로브 · CI). 그래서 약칭을 쓴 정규식은 **시험이 검증한 동작과
 * 기기에서 도는 동작이 다르다** — 시험이 초록이어도 그 초록이 기기를 말해 주지 않는다.
 * 2026.08.21 실측에서 앱 정규식 38개 중 **20개**가 이 부류였다.
 *
 * ## 무엇을 고르는가
 *
 * **뜻을 표기로 적는다**(규약 R-69). 아래 상수는 전부 **두 엔진에서 글자 단위로 같은 것**만
 * 골라 놓은 것이다 — 코드포인트 대조로 확인했다.
 *
 * - 수를 **파싱할** 자리는 [ASCII_DIGIT]. `Double.parseDouble`은 ASCII 숫자만 받으므로
 *   (`Integer.parseInt`는 유니코드 숫자도 받는다 — **둘이 다르다**) 그 밖을 통과시키면
 *   *파싱되지 않는 글자가 "수"로 실려 나간다.*
 * - 수를 **알아보고 지우기만** 할 자리는 [ANY_DIGIT]. 관용이 해롭지 않고 두 엔진에서 같다.
 * - 공백은 [WHITESPACE]. **ICU의 `\s`와 정확히 같은 25자**라 기기 동작이 바뀌지 않으면서
 *   데스크톱 쪽이 기기를 따라온다. 엑셀 헤더와 한국어 글에는 NBSP·전각 공백이 실제로 들어오고,
 *   그것을 공백으로 치는 것이 이 앱이 원하는 동작이다.
 *
 * **쓰지 말 것:** `\p{Alnum}` 같은 POSIX 이름은 ICU가 유니코드로 읽어 갈린다(실측: ICU 50,250 대
 * JVM 62). `[[:digit:]]`도 마찬가지다. `RegexOption.IGNORE_CASE`는 ICU가 완전 유니코드 접기를
 * 해서 갈린다(`ß`↔`SS` · `σ`↔`Σ` · `K`↔`U+212A`) — ASCII·한글만 다루는 자리에서만 쓴다.
 */
object RegexCharClasses {

    /**
     * 공백 — **안드로이드(ICU)의 `\s`와 글자 단위로 같다**(25자).
     *
     * 문자 클래스의 *내용*이다(대괄호는 쓰는 쪽이 붙인다). `\uXXXX` 표기를 쓰는 것은
     * 일부러다 — 날 제어문자를 소스에 넣지 않는다(R-37).
     */
    const val WHITESPACE: String =
        """\t\n\u000B\f\r \u0085\u00A0\u1680\u2000-\u200A\u2028\u2029\u202F\u205F\u3000"""

    /** ASCII 숫자 — **파싱할 수**에 쓴다(위 KDoc의 `parseDouble` 이야기). */
    const val ASCII_DIGIT: String = "0-9"

    /** 유니코드 십진 숫자 — **알아보고 지우기만** 할 때 쓴다. 두 엔진에서 같은 370자. */
    const val ANY_DIGIT: String = """\p{Nd}"""

    /**
     * 파일 이름에 남길 글자 — 두 엔진에서 같은 50,674자.
     *
     * ICU `\w`의 부분집합이고, 빠지는 것은 **파일 이름에 들어가면 곤란한 것들**이다
     * (ZWJ·ZWNJ 같은 보이지 않는 결합자, 원문자, 이음 문장부호).
     */
    const val FILENAME_KEEP: String = """\p{L}\p{M}\p{Nd}_"""

    /** 잇따른 공백 한 덩어리. */
    val WHITESPACE_RUN: Regex = Regex("""[$WHITESPACE]+""")

    /**
     * 값 분리 — 하이픈·슬래시·공백.
     *
     * **세 자리가 이것 하나를 봐야 한다**(`FieldValueSorter` · `BodyMeasurements.splitPlain` ·
     * `StatsDataProvider`). 종전에는 `Regex("[-/\\s]+")`가 세 벌로 적혀 있었고,
     * `BodyMeasurements`의 KDoc은 *"현행 인라인 파서와 같은 구분자를 쓴다"*고 적고 있었다 —
     * 같은 사실이 세 자리에 살면 한쪽이 반드시 낡는다.
     */
    val DASH_SLASH_WHITESPACE: Regex = Regex("""[\-/$WHITESPACE]+""")

    /** 헤더 대조용 잡음 — 공백·밑줄·하이픈·괄호(반각·전각). 엑셀 별칭 매칭이 쓴다. */
    val HEADER_NOISE: Regex = Regex("""[_\-()（）$WHITESPACE]""")
}

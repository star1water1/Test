package com.novelcharacter.app.util

/**
 * **수정일은 생성일보다 이를 수 없다** — 가져오기가 두 시각을 함께 쓰는 자리의 단일 소스
 * (순수 계층, Android 비의존).
 *
 * ## 왜 규칙이 필요했는가
 *
 * 두 시각의 처분이 **일부러 다르다.** '생성일'은 그 행의 정체라 파일 값으로 덮지 않고
 * (코드 열과 같은 취급), '수정일'은 왕복 충실성을 위해 **파일 값을 그대로** 받는다.
 * 갈라 둔 것 자체는 맞는데, 그 둘이 서로를 모르니 **짝이 어긋날 수 있었다.**
 *
 * 실제로 어긋나 있었다(2026.08.23 — 사용자가 내보낸 파일에서 찾았다):
 *
 * | '필드 템플릿' 행 | 생성일 | 수정일 |
 * |---|---|---|
 * | 천칭의 마법사 | 2026-08-02 10:29:05Z | **2026-03-20 14:40:23Z** |
 * | 별님대모험 | 2026-08-02 10:29:05Z | **2026-03-20 14:40:23Z** |
 *
 * 경위는 이렇다: 기본 프리셋을 다시 심으면(`UniverseViewModel.restoreBuiltInPresets`)
 * 두 시각이 *지금*으로 같이 선다. 그 뒤 **더 오래된 파일을 들이면** 생성일은 보호되는데
 * 수정일만 과거로 끌려간다. 그러면 그 열은 *"마지막으로 고친 때"*를 뜻하지 않게 되고,
 * 그 열로 정렬한 화면·파일이 조용히 틀린 차례를 낸다.
 *
 * ## 처방 — 받되, 생성일 아래로는 내리지 않는다
 *
 * 파일 값을 버리지 않는다(왕복 충실성은 그대로다). **생성일보다 이르면 생성일로 올려서**
 * 받을 뿐이다 — 그 행이 태어나기 전에 고쳐졌다는 말은 어느 쪽으로 읽어도 참이 아니다.
 *
 * **어긋난 행은 다시 들이면 스스로 낫는다:** 병합이 이 규칙을 지나므로, 같은 파일을
 * 그대로 다시 가져오면 수정일이 생성일로 올라가고 `content != existing`이 되어 갱신이 걸린다.
 */
object RecordTimestamps {

    /**
     * 이 행에 적을 수정일. 파일·기존 값이 [createdAt]보다 이르면 [createdAt]으로 올린다.
     *
     * @param createdAt 그 행의 생성일(정체라 덮이지 않는 쪽)
     * @param updatedAt 부르는 쪽이 고른 수정일(파일 값 → 기존 값 → 지금의 순서로 이미 접힌 것)
     */
    fun orderedUpdatedAt(createdAt: Long, updatedAt: Long): Long = maxOf(createdAt, updatedAt)
}

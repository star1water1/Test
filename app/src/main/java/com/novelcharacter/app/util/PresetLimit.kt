package com.novelcharacter.app.util

/**
 * 프리셋 개수의 **권고 한도** — 목록 프리셋·검색 프리셋이 공유하는 단일 소스 (B-75).
 *
 * ## 법이 아니라 권고다 (2026.08.03 사용자 확정 — 확정 문서 1장 19번, 답 ㄱ1)
 * 종전에는 같은 수 20을 **경로마다 다르게** 다뤘다: 인앱 저장은 21번째에서 예외를 던져
 * **하드 차단**했고, 엑셀 가져오기는 초과를 **수용**하면서 같은 값을 *"인앱 권장 한도"*라
 * 불렀다. 그래서 21개를 원하는 사용자에게 **인앱 확장 경로가 아예 없었다**(재단 — 원칙 01).
 * 파일을 고쳐 넣으면 되는데 앱에서는 못 한다는 것이 특히 어긋난 자리다.
 *
 * 확정은 **엑셀 쪽 동작으로 통일**한다 — 넘어도 저장하고, 넘었다는 사실과 정리 경로를 말한다.
 * 그것이 검증 → 알림 → 바로잡을 경로의 순서이고(개발 의도 2번), 저장을 막는 것은 그 순서의
 * 첫 걸음에서 사용자의 데이터를 되돌려 보내는 일이다.
 *
 * ## 한도 자체는 남긴다
 * 0으로 두지 않는 것은 **칩 줄이 실제로 길어지기 때문**이다 — 두 화면 다 프리셋을 한 줄
 * 칩으로 그린다(`presetChipGroup`). 수를 재서 말해 주는 것과 막는 것은 다른 일이라,
 * 재는 쪽만 남긴다.
 */
object PresetLimit {

    /** 권고 한도. **넘어도 저장은 된다** — 판정은 [exceeded]가 든다. */
    const val RECOMMENDED_MAX = 20

    /**
     * 지금 [totalCount]개가 있는 상태가 권고를 넘었는가.
     *
     * **묻는 자리는 언제나 *저장·가져오기가 끝난 뒤*다** — 인앱 저장 뒤(`exceedsRecommended`)와
     * 엑셀 가져오기 집계 뒤, 둘뿐이다. *저장 전에* 묻는 짝(`wouldExceed`)을 두지 않은 것은
     * **쓸 자리가 없기 때문**이다: 막지 않기로 한 이상 미리 아는 것이 바꾸는 동작이 없고,
     * 창을 열기 전에 말하면 *"넘겠지만 어차피 저장된다"*는 빈 경고가 된다(종전의 하드 차단이
     * 정확히 그 자리에서 저장을 되돌려 보냈다). 쓰이지 않는 짝을 남겨 두면 다음 사람이
     * **경계가 둘이라고 읽는다.**
     */
    fun exceeded(totalCount: Int): Boolean = totalCount > RECOMMENDED_MAX
}

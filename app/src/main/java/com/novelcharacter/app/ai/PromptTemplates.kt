package com.novelcharacter.app.ai

/**
 * **AI에 보내는 메시지 양식의 단일 소스** — 기본 양식 열넷과 그 자리표 어휘 (순수).
 *
 * ## 왜 있는가 — 사용자 요청 2026.08.20
 *
 * *"ai api에 보내지는 메세지 양식도 모두 사용자가 편집할 수 있게 하기(인앱, 엑셀 모두)."*
 *
 * 종전에는 프롬프트 열넷이 전부 각 서제스터의 `companion object` 안에 **하드코딩된 문자열**
 * 이었다. 앱이 무엇을 보내는지 볼 수도, 고칠 수도 없었다 — 원칙 01(열린 구조)이 정면으로
 * 겨누는 자리이고, *"개발자가 예상한 범위 안에서만 쓰는 앱이 아니"*라는 개발 의도와도
 * 어긋난다. 어떤 말투로 물어야 좋은 답이 오는지는 작품·모델·사용자마다 다르고, 그것은
 * 개발자가 정할 수 없다(자율성 우선).
 *
 * ## 무엇을 열고 무엇을 잠갔는가
 *
 * **판단 기준 한 줄: 사용자가 지워도 앱이 "무엇이 빠졌는지" 말할 수 있으면 연다.
 * 지우면 앱이 오진할 수밖에 없으면 잠근다.**
 *
 * - **연 것** — 역할 선언·규칙 본문·재료를 싣는 차례와 이름표. 규칙을 지우면 추천 품질이
 *   떨어지지만 앱은 그 결손을 세어서 말한다(`MissingCause`). 열화이지 오진이 아니다.
 * - **잠근 것** — 응답 형식 지시([responseFormat])와 `[추천할 필드]` 절. 배열 이름 하나만
 *   달라져도 응답을 읽는 쪽이 **0건**을 보고, 사용자는 *"형식 오류"*라는 거짓 진단과 함께
 *   돈을 낸 요청을 통째로 잃는다.
 *
 * 잠그는 방식은 *"앱이 뒤에 몰래 붙인다"*가 아니라 **필수 자리표**다 — 자리는 사용자가
 * 정하고 내용은 앱이 만든다. 빠지거나 두 번 나오면 저장 자체를 거절하고 그 사실을 말한다
 * ([PromptTemplateValidator]). 수식 편집이 *"그대로 저장"*을 열어 둔 것과 갈리는 이유는,
 * 수식에는 *"아직 안 만든 필드를 먼저 참조해 둔다"*는 정당한 사유가 있지만 자리표 어휘는
 * **앱이 정하는 닫힌 목록**이라 모르는 이름은 100% 오타이기 때문이다. 오타는 글자 그대로
 * 실려 나가 **돈을 내고 망가진 요청**이 된다.
 *
 * ## 이미지 절은 여기 없다
 *
 * *"이미지 N장이 함께 실려 있다"*는 [AiRequest.imageSystemRule]로만 다닌다(B-139) —
 * 이미지가 빠지는 경로가 둘이라, 양식에 섞으면 그 둘이 각자 걷어내야 하고 하나만 빠뜨려도
 * **없는 그림을 근거로 삼으라는 지시가 나간다.** `tools/check_ai_image_rule.sh`가 잠근다.
 */
object PromptTemplates {

    /**
     * 양식 공급자 — **순수 계층이 사용자 양식을 받는 유일한 통로**.
     *
     * 조립기가 `AiPromptSettings`를 직접 쥐면 `Context`가 딸려 와 순수 JVM 시험이 프롬프트를
     * 통째로 못 본다(`ImageBatchTagSuggester`가 정확히 그 사고로 생성자를 람다 셋으로 갈랐다).
     * 그래서 저장소는 화면·모델 계층이 쥐고 여기로는 **함수 하나만** 건네준다.
     */
    fun interface Source {
        fun templateOf(id: Id): String

        companion object {
            /** 고치지 않은 상태 — 시험과 기본 인자가 쓴다. */
            val DEFAULTS = Source { default(it) }
        }
    }

    /** 한 양식이 요청의 어느 자리에 실리는가. */
    enum class Kind {
        /** 모델의 역할·규칙 — 프로토콜마다 `system`/`system_instruction`/첫 메시지로 간다. */
        SYSTEM,

        /** 이번 요청의 재료 — 사용자 메시지. */
        USER
    }

    /**
     * 편집 대상 양식 열넷.
     *
     * **연결 확인 핑은 여기 없다**(`AiService`의 `"Reply with only the word OK."`) — 기능
     * 프롬프트가 아니라 *연결이 되는가*의 정의라, 고칠 수 있게 하면 무엇을 확인하는지가
     * 사라진다.
     *
     * @param key 저장 키이자 '앱 설정' 시트의 `설정키`. **바꾸면 옛 파일이 그 양식을 잃는다.**
     * @param axisLabel 사람이 읽는 기능 이름. 화면과 엑셀 `설명` 칸이 같은 말을 쓰도록
     *   여기 한 벌만 둔다(두 자리에 적으면 한쪽이 낡는다).
     */
    enum class Id(val key: String, val axisLabel: String, val kind: Kind) {
        CHAR_FIELD_SYSTEM("ai_tpl_char_field_system", "캐릭터 필드 추천", Kind.SYSTEM),
        CHAR_FIELD_USER("ai_tpl_char_field_user", "캐릭터 필드 추천", Kind.USER),
        EVENT_FIELD_SYSTEM("ai_tpl_event_field_system", "사건 필드 추천", Kind.SYSTEM),
        EVENT_FIELD_USER("ai_tpl_event_field_user", "사건 필드 추천", Kind.USER),
        NARRATIVE_SYSTEM("ai_tpl_narrative_system", "서술형 작성", Kind.SYSTEM),
        NARRATIVE_USER("ai_tpl_narrative_user", "서술형 작성", Kind.USER),
        NAME_SYSTEM("ai_tpl_name_system", "이름 추천", Kind.SYSTEM),
        NAME_USER("ai_tpl_name_user", "이름 추천", Kind.USER),
        VALUE_LIBRARY_SYSTEM("ai_tpl_value_library_system", "값 라이브러리 정리", Kind.SYSTEM),
        VALUE_LIBRARY_USER("ai_tpl_value_library_user", "값 라이브러리 정리", Kind.USER),
        FOLDER_TAG_SYSTEM("ai_tpl_folder_tag_system", "폴더 이름 태그 제안", Kind.SYSTEM),
        FOLDER_TAG_USER("ai_tpl_folder_tag_user", "폴더 이름 태그 제안", Kind.USER),
        IMAGE_TAG_SYSTEM("ai_tpl_image_tag_system", "이미지 태그 제안", Kind.SYSTEM),
        IMAGE_TAG_USER("ai_tpl_image_tag_user", "이미지 태그 제안", Kind.USER);

        /** `캐릭터 필드 추천 — 지시문` 꼴. 목록·시트가 같은 말을 쓴다. */
        val label: String
            get() = axisLabel + " — " + if (kind == Kind.SYSTEM) "지시문" else "재료"

        companion object {
            fun ofKey(key: String): Id? = entries.firstOrNull { it.key == key }
        }
    }

    /**
     * 한 자리표의 선언.
     *
     * @param meaning 사람이 읽는 뜻. 엑셀 `설명` 칸과 편집 창의 자리표 목록이 이것을 쓴다 —
     *   **문구에 이름을 손으로 적지 않는다**(적으면 자리표를 늘릴 때 안내가 거짓이 된다.
     *   수식 도움말이 `avg`를 빠뜨린 채 서 있던 것이 그 전례다).
     * @param required 빠지면 저장을 거절하는가. 응답을 읽는 계약이 걸린 자리뿐이다.
     * @param single 두 번 나오면 거절하는가. **앱이 만드는 덩어리**(형식 지시·필드 목록·값
     *   목록)에만 건다 — 두 벌이면 서로 모순된 지시가 되고 토큰 값도 두 배로 나간다.
     *   개수·모드처럼 짧은 값은 사용자가 두 자리에서 되뇌어도 손해가 없어 걸지 않는다.
     */
    data class Token(
        val name: String,
        val meaning: String,
        val required: Boolean = false,
        val single: Boolean = false
    )


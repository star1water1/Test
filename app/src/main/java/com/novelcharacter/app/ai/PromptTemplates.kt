    /**
     * **값이 있는데 양식에 자리가 없어 안 실린 재료**의 고지 문구 (R-14의 뒷면).
     *
     * 앞면(사용자가 뺀 재료를 *잘렸다*고 말하지 않기)은 조립기가 `used`로 처리한다. 이쪽은
     * 그 반대다 — `{{메모}}`를 지운 사용자가 추천이 빈약해진 이유를 **가릴 수 있어야 한다.**
     * 조용히 빠지면 사용자는 설정을 뒤지고, 없는 설정을 찾다 못 찾는다(변수 제어).
     *
     * 사건 축이 *"사용자가 끈 재료"*를 이미 갈라 고지하는 것과 같은 대칭이다.
     *
     * @param present 재료 이름 → **그 캐릭터·사건에 실제로 값이 있는가**.
     */
    fun unusedMaterialNotes(used: Set<String>, present: Map<String, Boolean>): List<String> =
        present.filter { (name, has) -> has && name !in used }
            .map { (name, _) -> wrap(name) + " 자리가 양식에 없어 그 재료를 싣지 않았습니다" }

    fun requiredTokensOf(id: Id): List<String> = tokensOf(id).filter { it.required }.map { it.name }

    /** 두 번 나오면 안 되는 자리표 — 앱이 만드는 덩어리뿐이다. */
    fun singleTokensOf(id: Id): List<String> = tokensOf(id).filter { it.single }.map { it.name }


package com.novelcharacter.app.excel

/**
 * **같은 사유로 줄이 쏟아지는 고지를 접는다** — 앞 [HEAD]줄 + 나머지 건수 한 줄.
 *
 * ## 왜 접는가 — 실측이 근거다
 *
 * 고지를 버리는 것은 답이 아니다(개발 의도 2번 — 말없이 유실되지 않는다). 그러나 행마다
 * 한 줄씩 쌓이는 고지는 **진짜 경고를 자기 길이로 묻는다**: 빈 앱 복원에서 "코드가 기존에
 * 없어 새로 생성됨"이 S25 실측 한 번에 **3836줄**이었고, 상세·이력의 길이 상한에 다른
 * 경고가 통째로 밀려 나갔다(PR #439).
 *
 * 그래서 **수는 끝까지 세고 줄만 묶는다** — 사용자는 *몇 건인지*를 그대로 듣고,
 * 그중 앞 몇 건을 예시로 본다. 규약 R-14(잘라낸 것은 개수로 존재를 알린다)의 실행이다.
 *
 * ## 왜 접는 규칙이 이 파일에 있는가
 *
 * 접는 자리가 둘 이상이면 **상한이 자리마다 갈린다** — 한쪽은 20에서, 다른 쪽은 50에서
 * 접히면 같은 파일을 들인 사용자가 범주마다 다른 규칙을 겪는다. 꼬리 문구만 부르는 쪽이
 * 정하고(범주마다 세는 단위와 처방이 다르다) 접는 셈은 여기 하나다.
 */
object ImportWarningFold {

    /** 이 수까지는 행별로 그대로 싣는다. */
    const val LIST_CAP = 20

    /** 상한을 넘으면 앞 이만큼만 예시로 싣고 나머지는 한 줄로 센다. */
    const val HEAD = 10

    /**
     * [lines]를 접는다. [total]은 **줄을 쥐지 않은 몫까지 포함한 전체 건수**다
     * (부르는 쪽이 상한까지만 줄을 쥐고 수는 끝까지 세는 것이 이 함수의 전제다).
     *
     * [tail]은 꼬리 한 줄을 만든다 — 남은 건수와 전체 건수를 받는다.
     */
    fun fold(
        lines: List<String>,
        total: Int,
        cap: Int = LIST_CAP,
        head: Int = HEAD,
        tail: (remaining: Int, total: Int) -> String
    ): List<String> {
        if (total <= cap) return lines
        return lines.take(head) + tail(total - head, total)
    }
}
